"""
Tipos de datos
String: str
"""

# Declararemos una variable tipo cadena de texto
nombre = "Alejandro Magdiel Corahua"

# Convertimos todos los caracteres a mayúsculas
print(nombre.upper())

# Convertimos todos los caracteres a minúsculas
print(nombre.lower())

# Convertimos la primera letra de cada palabra a mayúscula
print(nombre.title())

# Calculamos la cantidad total de caracteres
# La función len() también cuenta los espacios
print(len(nombre))